#!/usr/bin/env python3
"""Generate paper/numbers.tex and paper/tables/*.tex from results/.

Usage: experiments/paper_numbers.py

Every number the paper states is a macro defined here from a results file,
so the text and the evaluation cannot drift apart. Macro names are
\\N<Subject><Config><Quantity>, e.g. \\NLinuxDefconfigTP. Missing inputs are
skipped with a warning, so the script can run on a partial pipeline.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from subjects import EVIDENCE, RESULTS, ROOT, SUBJECTS  # noqa: E402

PAPER = ROOT / "paper"
HOST_PREFIXES = ("scripts/", "tools/", "build/util/")  # host tools, not target code

macros = {}


def name(*parts):
    words = []
    for p in parts:
        for w in re.split(r"[^A-Za-z0-9]+", str(p)):
            if w:
                w = re.sub(r"\d", lambda m: "ZOTTFFSSEN"[int(m.group())], w)  # no digits in macros
                words.append(w[0].upper() + w[1:])
    return "N" + "".join(words)


def fmt(v):
    if isinstance(v, float):
        return f"{v:,.1f}" if v < 1000 else f"{v:,.0f}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def define(value, *parts):
    macros[name(*parts)] = fmt(value)
    return fmt(value)


def load(path):
    p = RESULTS / path
    if not p.exists():
        print("warning: missing", p, file=sys.stderr)
        return None
    return json.loads(p.read_text())


def pct(a, b):
    return round(100.0 * a / b, 1) if b else 0.0


def agreement():
    rows = {}
    for s, spec in SUBJECTS.items():
        d = load(f"agreement/{s}.full.json")
        if not d:
            continue
        define(d["makefile_instances"], s, "instances")
        define(d["objects"], s, "objects")
        define(d["kinds"].get("target", 0), s, "targets")
        define(d["kinds"].get("member", 0), s, "members")
        for config, v in d["profiles"].items():
            m, t = v["members"], v["targets"]
            host = sum(p.startswith(HOST_PREFIXES) for p in m["outside_universe_paths"])
            fp_sel = m["fp"] - m["fp_build_failed"]
            r = {"pred": m["predicted"], "tp": m["tp"], "fp": fp_sel, "fpbuild": m["fp_build_failed"],
                 "fn": m["fn_within_universe"], "out": m["outside_universe"], "outhost": host,
                 "outtarget": m["outside_universe"] - host, "physical": m["physical"], "prec": pct(m["tp"], m["tp"] + fp_sel),
                 "overlap": m["overlap_pct"], "overlapnohost": pct(m["tp"], m["physical"] - host),
                 "targetsoverlap": t["overlap_pct"]}
            for k, val in r.items():
                define(val, s, config, k)
            rows[(s, config)] = r
    return rows


def table(path, header, lines):
    (PAPER / "tables").mkdir(exist_ok=True)
    (PAPER / "tables" / path).write_text(
        "% Generated by experiments/paper_numbers.py -- do not edit.\n" + "\n".join(lines) + "\n")


LINUX_LABELS = {"tinyconfig": "\\texttt{tinyconfig} (i386)", "defconfig": "\\texttt{defconfig} (x86-64)",
                "debian": "Debian (x86-64)", "allmodconfig": "\\texttt{allmodconfig} (x86-64)"}


def agreement_tables(rows):
    lab = LINUX_LABELS
    lines = []
    for c in ("tinyconfig", "defconfig", "debian", "allmodconfig"):
        r = rows.get(("linux", c))
        if r:
            lines.append(f"{lab[c]} & {fmt(r['physical'])} & {fmt(r['pred'])} & {fmt(r['tp'])} & "
                         f"{fmt(r['fp'])} & {fmt(r['fn'])} & {fmt(r['out'])} ({fmt(r['outhost'])}) & "
                         f"{r['prec']:.1f}\\% & {r['overlap']:.1f}\\% & {r['targetsoverlap']:.1f}\\% \\\\")
    table("linux_agreement.tex", None, lines)
    lines = []
    for s in ("busybox", "barebox", "uboot", "coreboot"):
        for c in SUBJECTS[s]["configs"]:
            r = rows.get((s, c))
            if r:
                lines.append(f"{SUBJECTS[s]['name']} & {fmt(r['physical'])} & {fmt(r['pred'])} & {fmt(r['tp'])} & "
                             f"{fmt(r['fp'])} & {fmt(r['fpbuild'])} & {fmt(r['fn'])} & {fmt(r['out'])} "
                             f"({fmt(r['outhost'])}) & {r['prec']:.1f}\\% & {r['overlap']:.1f}\\% \\\\")
    table("other_agreement.tex", None, lines)


def subjects_table():
    builds = load("builds.json") or {}
    lines = []
    for s, spec in SUBJECTS.items():
        for c, cfg in spec["configs"].items():
            b = builds.get(f"{s}:{c}")
            if not b or cfg.get("build", True) is False:
                continue
            define(b["objects"], s, c, "physical", "objects")
            define(round(b["seconds"] / 60, 1), s, c, "build", "minutes")
            label = LINUX_LABELS.get(c, f"\\texttt{{{c}}}") if s == "linux" else f"\\texttt{{{c}}}"
            lines.append(f"{spec['name']} & {spec['version']} & {label.replace('_', r'\_')} & {fmt(b['objects'])} \\\\")
        define(spec["version"], s, "version")
    table("subjects.tex", None, lines)


def ablations():
    for s in SUBJECTS:
        full = load(f"agreement/{s}.full.json")
        if not full:
            continue
        for v in ("no_includes", "no_rules", "no_link_semantics"):
            d = load(f"agreement/{s}.{v}.json")
            if not d:
                continue
            define(full["objects"] - d["objects"], s, v, "lost", "objects")
            for c, p in d["profiles"].items():
                m = p["members"]
                define(m["fp"] - m["fp_build_failed"], s, v, c, "fp")
                define(m["overlap_pct"], s, v, c, "overlap")
                define(m["fn_within_universe"], s, v, c, "fn")


def timing():
    d = load("timing.json")
    if not d:
        return
    lines = []
    for s in sorted(d, key=["busybox", "barebox", "uboot", "coreboot", "linux"].index):
        v = d[s]
        define(v["median_seconds"], s, "seconds")
        define(v["max_peak_rss_mb"], s, "rss")
        run = v["runs"][0]
        define(run["z3_checks"], s, "z3checks")
        lines.append(f"{SUBJECTS[s]['name']} & {fmt(run['makefile_instances'])} & {fmt(run['objects'])} & "
                     f"{v['median_seconds']:.2f} & {v['max_peak_rss_mb']:.0f} \\\\")
    table("timing.tex", None, lines)


def kmax():
    for s in ("busybox", "linux"):
        d = load(f"kmax/{s}.json")
        if not d:
            continue
        if d.get("run"):
            define(round(d["run"]["time_s"]), s, "kmax", "seconds")
            define(round(d["run"]["maxrss_mb"] / 1024, 1), s, "kmax", "rss", "gb")
        define(len(d.get("unexpanded_paths", [])), s, "kmax", "unexpanded")
        define(d["objects"], s, "kmax", "objects")
        for c, p in d["profiles"].items():
            for view in ("local", "with_dirs"):
                m = p[view]
                define(m["precision_pct"], s, "kmax", c, view, "prec")
                define(m["overlap_pct"], s, "kmax", c, view, "overlap")
                define(m["fn_within_universe"], s, "kmax", c, view, "fn")
                define(m["tp"], s, "kmax", c, view, "tp")
                if "fn_kfold_kinds" in m:
                    define(m["fn_kfold_kinds"].get("member", 0), s, "kmax", c, view, "fn", "members")


def bench():
    d = load("bench_scaling.json")
    if not d:
        return
    rows = {}
    for r in d["runs"]:
        rows.setdefault(r["k"], {})[r["family"]] = r
    lines = []
    for k in sorted(rows):
        R = rows[k]

        def fork(fam):
            x = R.get(fam, {}).get("kfold_fork", {})
            if x.get("status") == "ok":
                return f"{fmt(x['states'])} / {x['time_s']:.2f}"
            return {"timeout": "t/o", "skipped": "--"}.get(x.get("status"), "--")
        kf = max(R[f]["kfold"]["time_s"] for f in R)
        km = max(R[f]["kmax"]["time_s"] for f in R)
        lines.append(f"{k} & {fork('ifeq')} & {fork('value')} & {fork('indirect')} & {kf:.2f} & {km:.2f} \\\\")
        for fam, r in R.items():
            f = r.get("kfold_fork", {})
            if f.get("status") == "ok":
                define(f["states"], "bench", fam, k, "states")
                define(f["time_s"], "bench", fam, k, "seconds")
    table("scaling.tex", None, lines)
    define(d["timeout_s"], "bench", "timeout")
    define(max(r["k"] for r in d["runs"]), "bench", "maxk")
    for tool in ("kfold", "kmax", "kmax_smt"):
        ok = [r[tool] for r in d["runs"] if r.get(tool, {}).get("status") == "ok"]
        define(f"{min(x['time_s'] for x in ok):.2f}", "bench", tool, "min", "seconds")
        define(f"{max(x['time_s'] for x in ok):.2f}", "bench", tool, "max", "seconds")
        define(round(max(x["maxrss_mb"] for x in ok)), "bench", tool, "max", "rss")
        define(sum(not x.get("exact") for x in ok), "bench", tool, "inexact")
        define(len(ok), "bench", tool, "runs")


def devtasks():
    d = load("devtasks/why.json")
    if d:
        cases = sum(c["cases"] for c in d["configs"].values())
        correct = sum(c["correct"] for c in d["configs"].values())
        define(cases, "why", "cases")
        define(correct, "why", "correct")
        define(len(d["configs"]), "why", "configs")
        define(d["sample_per_side"], "why", "per", "side")
        kinds = {}
        for c in d["configs"].values():
            for k, n in c.get("failing_kinds", {}).items():
                kinds[k] = kinds.get(k, 0) + n
        for k, n in kinds.items():
            define(n, "why", "fail", k)
    d = load("devtasks/config_for.json")
    if d:
        from devtasks import compilable
        rows = d["rows"]
        define(len(rows), "configfor", "commits")
        define(sum(map(compilable, rows)), "configfor", "selectable")
        mapped = [r for r in rows if r["result"].get("objects")]
        define(len(rows) - len(mapped), "configfor", "unmapped")
        define(sum(bool(r["result"].get("excluded")) for r in mapped), "configfor", "excluded")
        define(sum(len(r["result"].get("excluded") or {}) for r in mapped), "configfor", "excluded", "objects")
        define(sum(bool((r["result"].get("verify") or {}).get("lost")) for r in mapped), "configfor", "lost")
        define(sum(len(r["result"]["objects"]) for r in mapped), "configfor", "objects")
        secs = sorted(r["seconds"] for r in rows)
        define(round(secs[len(secs) // 2], 1), "configfor", "median", "seconds")
    d = load("devtasks/config_for_compile.json")
    if d:
        define(d["sampled"], "compile", "sampled")
        define(d["all_compiled"], "compile", "ok")
    d = load("devtasks/blindspots.json")
    if d and isinstance(d.get("result"), dict):
        res = d["result"]
        for k in ("objects_considered", "blind_spots", "entries_with_blind_spots"):
            if k in res:
                define(res[k], "blind", k)
        reasons = list({o: r for e in res.get("top_entries", []) for o, r in e["objects"]}.values())
        define(sum(r.startswith("non-x86 arch") for r in reasons), "blind", "arch")
        define(sum(r.startswith("other: not enabled") for r in reasons), "blind", "notenabled")
        define(sum(r == "other" for r in reasons), "blind", "nopivot")


def kconfig_check():
    d = load("kconfig_check.json")
    if not d:
        return
    for c, v in d.items():
        define(v["symbols_in_config"], "kconfig", c, "symbols")
        define(len(v["mismatches"]), "kconfig", c, "mismatches")
    define(sum(len(v["mismatches"]) for v in d.values()), "kconfig", "mismatches")
    define(sum(len(v.get("smt_violations", [])) for v in d.values()), "kconfig", "smt", "violations")
    define(len(d), "kconfig", "configs")
    define(next(iter(d.values()))["defined_symbols"], "kconfig", "defined")


def main():
    rows = agreement()
    agreement_tables(rows)
    subjects_table()
    ablations()
    timing()
    kmax()
    bench()
    devtasks()
    kconfig_check()
    lines = ["% Generated by experiments/paper_numbers.py from results/ -- do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}\\xspace}}" for k, v in sorted(macros.items())]
    (PAPER / "numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(macros)} macros to paper/numbers.tex")


if __name__ == "__main__":
    main()
